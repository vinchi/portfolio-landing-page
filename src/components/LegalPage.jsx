export default function LegalPage({ activeKey = 'terms', onSelectDoc, onBackHome }) {
  const doc = LEGAL_DOCS[activeKey] || LEGAL_DOCS.terms
  const Icon = doc.icon

  return (
    <section className="section legal-section">
      <div className="container">
        <div className="legal-container">
          {/* 상단 문서 전환 탭 */}
          <div className="legal-tabs">
            {Object.values(LEGAL_DOCS).map((item) => (
              <button
                key={item.key}
                type="button"
                onClick={() => onSelectDoc(item.key)}
                className={`admin-tab-btn ${item.key === doc.key ? 'active' : ''}`}
              >
                <span>{item.title}</span>
              </button>
            ))}
          </div>

          {/* 문서 본문 카드 */}
          <article className="glass-card legal-card">
            <div className="legal-header">
              <div className="icon-box">
                <Icon size={22} />
              </div>
              <div style={{ flex: 1 }}>
                <span className="section-eyebrow" style={{ marginBottom: '4px' }}>
                  시행일: {doc.updatedAt} · 개정 버전 {doc.version}
                </span>
                <h1 className="legal-title">{doc.title}</h1>
                <p className="legal-subtitle">{doc.subtitle}</p>
              </div>
            </div>

            {/* 빠른 조항 목차 */}
            <nav className="legal-toc" aria-label="조항 목차">
              {doc.sections.map((sec, idx) => (
                <button
                  key={sec.heading}
                  type="button"
                  className="legal-toc-chip"
                  onClick={() => {
                    const el = document.getElementById(`legal-sec-${idx}`)
                    if (el) el.scrollIntoView({ behavior: 'smooth', block: 'start' })
                  }}
                >
                  {sec.heading}
                </button>
              ))}
            </nav>

            <div className="legal-body">
              {doc.sections.map((sec, idx) => (
                <div key={sec.heading} id={`legal-sec-${idx}`} className="legal-block">
                  <h3>{sec.heading}</h3>
                  <p>{sec.body}</p>

                  {/* 표(Table) 데이터가 있는 조항은 표로 깔끔하게 렌더링 */}
                  {sec.table && (
                    <div className="legal-table-wrap">
                      <table className="legal-table">
                        <thead>
                          <tr>
                            {sec.table.headers.map((h) => (
                              <th key={h}>{h}</th>
                            ))}
                          </tr>
                        </thead>
                        <tbody>
                          {sec.table.rows.map((row, rIdx) => (
                            <tr key={rIdx}>
                              {row.map((cell, cIdx) => (
                                <td key={cIdx}>{cell}</td>
                              ))}
                            </tr>
                          ))}
                        </tbody>
                      </table>
                    </div>
                  )}
                </div>
              ))}
            </div>

            <div className="legal-footer-actions">
              <button
                type="button"
                onClick={() => window.scrollTo({ top: 0, behavior: 'smooth' })}
                className="btn btn-glass btn-sm"
              >
                <ArrowUp size={15} />
                <span>맨 위로</span>
              </button>
              <button type="button" onClick={onBackHome} className="btn btn-primary btn-sm">
                <ArrowLeft size={16} />
                <span>홈페이지로 돌아가기</span>
              </button>
            </div>
          </article>
        </div>
      </div>
    </section>
  )
}
